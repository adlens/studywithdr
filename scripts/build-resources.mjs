function validate(items) {
  const errors = [];
  const seen = { slug: new Map(), title: new Map(), url: new Map() };
  const typeSlugs = SWD.RESOURCE_TYPES.map((t) => t.slug);
  const boardSlugs = SWD.EXAM_BOARD_OPTIONS.map((b) => b.slug);

  items.forEach((item, i) => {
    const where = `Resource #${i + 1} (${item.slug || item.title || 'untitled'})`;
    const fail = (msg) => errors.push(`${where}: ${msg}`);

    for (const field of ['slug', 'status', 'title', 'subject', 'level', 'resource_type', 'description', 'url', 'date_published']) {
      if (!item[field] || typeof item[field] !== 'string') fail(`"${field}" is required.`);
    }
    if (item.slug && !/^[a-z0-9]+(-[a-z0-9]+)*$/.test(item.slug)) fail('"slug" must use lowercase letters, numbers and hyphens only.');
    if (item.slug === 'index') fail('"index" is reserved.');
    if (item.status && !['published', 'draft'].includes(item.status)) fail('"status" must be "published" or "draft".');
    if (item.subject && item.level && !SWD.getCategoryBySlug(`${item.subject}-${item.level}`)) {
      const levels = SWD.getLevelsForSubject(item.subject).map((l) => l.slug);
      fail(levels.length
        ? `unknown level "${item.level}" for ${item.subject}. Use one of: ${levels.join(', ')}.`
        : `unknown subject "${item.subject}". Use one of: ${SWD.RESOURCE_SUBJECTS.map((s) => s.slug).join(', ')}.`);
    }
    if (item.exam_board && !boardSlugs.includes(item.exam_board)) fail(`unknown "exam_board". Use one of: ${boardSlugs.join(', ')}.`);
    if (item.resource_type && !typeSlugs.includes(item.resource_type)) fail(`unknown "resource_type". Use one of: ${typeSlugs.join(', ')}.`);
    if (!Array.isArray(item.topics)) {
      fail('"topics" must be a list, e.g. ["Vectors", "Integration"] (or [] for none).');
    } else {
      const lower = item.topics.map((t) => String(t).trim().toLowerCase());
      if (lower.some((t) => !t)) fail('"topics" contains an empty tag.');
      if (new Set(lower).size !== lower.length) fail('"topics" contains the same tag twice.');
    }
    if (item.url && !/^https:\/\/payhip\.com\//.test(item.url)) fail('"url" must be a Payhip link (https://payhip.com/...).');
    for (const field of ['date_published', 'date_modified']) {
      if (item[field] && !/^\d{4}-\d{2}-\d{2}$/.test(item[field])) fail(`"${field}" must look like 2026-10-08.`);
    }
    if (item.cover_image) {
      if (!item.cover_image.startsWith('/images/')) fail('"cover_image" must be a path like /images/my-cover.png.');
      else if (!fs.existsSync(path.join(ROOT, item.cover_image))) fail(`cover image not found: ${item.cover_image}`);
    }

    for (const key of ['slug', 'title', 'url']) {
      const value = String(item[key] || '').toLowerCase();
      if (!value) continue;
      if (seen[key].has(value)) fail(`duplicate "${key}" (also used by resource #${seen[key].get(value) + 1}).`);
      else seen[key].set(value, i);
    }
  });

  return errors;
}

const errors = validate(catalog);
if (errors.length) {
  console.error('Catalogue has problems. Nothing was built.\n');
  errors.forEach((e) => console.error(`  - ${e}`));
  process.exit(1);
}

