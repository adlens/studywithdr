const jsonLd = (data) =>
  `<script type="application/ld+json">\n${JSON.stringify(data, null, 2).replace(/</g, '\\u003c')}\n    </script>`;

function replaceBetween(text, name, content, indent) {
  const start = `<!-- generated:${name}:start -->`;
  const end = `<!-- generated:${name}:end -->`;
  const from = text.indexOf(start);
  const to = text.indexOf(end);
  if (from === -1 || to === -1) throw new Error(`Missing ${name} markers`);
  return text.slice(0, from + start.length) + '\n' + content + '\n' + indent + text.slice(to);
}

function breadcrumbs(trail) {
  return {
    '@type': 'BreadcrumbList',
    itemListElement: trail.map(([name, url], i) => ({ '@type': 'ListItem', position: i + 1, name, item: url }))
  };
}

function truncate(text, max) {
  if (text.length <= max) return text;
  return text.slice(0, text.lastIndexOf(' ', max - 1)).replace(/[,;:]$/, '') + '…';
}

function formatDate(iso) {
  return new Date(`${iso}T12:00:00Z`).toLocaleDateString('en-GB', {
    day: 'numeric', month: 'long', year: 'numeric', timeZone: 'Europe/London'
  });
}

const capitalise = (text) => text.charAt(0).toUpperCase() + text.slice(1);

// Fills in everything a resource page needs, so `page` content is optional.
function resolve(item) {
  const page = item.page || {};
  const row = SWD.mapCatalogItem(item);
  const cat = SWD.getCategoryBySlug(row.category_slug);
  const typeName = SWD.getResourceTypeName(item.resource_type);
  const isFree = String(row.price).toLowerCase() === 'free';
  const label = row.qualification;

  return {
    item,
    row,
    url: SITE + SWD.getResourcePagePath(item),
    typeName,
    isFree,
    label,
    priceLabel: [isFree ? 'Free' : '', row.format].filter(Boolean).join(' '),
    ctaLabel: item.cta_label || (isFree && row.format ? `Get the Free ${row.format}` : isFree ? 'Get it free' : 'View on Payhip'),
    dateModified: item.date_modified || item.date_published,
    image: item.cover_image || DEFAULT_IMAGE,
    h1: page.h1 || item.title,
    titleTag: page.title_tag || `${item.title} | ${label} ${typeName} | Study with Dr`,
    metaDescription: page.meta_description || truncate(item.description, 160),
    subtitle: page.subtitle || capitalise(`${isFree ? 'free ' : ''}${typeName.toLowerCase()} for ${label}.`),
    educationalLevel: page.educational_level || (cat ? cat.levelName : ''),
    subjectName: cat ? cat.subjectName : '',
    alignment: page.alignment,
    introHeading: page.intro_heading || 'About this resource',
    intro: page.intro || [item.description],
    coversHeading: page.covers_heading || 'Topics covered',
    covers: page.covers || item.topics,
    scopeNote: page.scope_note || '',
    keyIdeas: page.key_ideas || [],
    tuitionHeading: page.tuition_heading || 'Want one-to-one help?',
    tuitionText: page.tuition_text || `Study with Dr offers one-to-one online ${cat ? cat.subjectName : ''} tuition, from 11+ and GCSE through to A-Level and university.`,
    tuitionCta: page.tuition_cta || 'Enquire about tuition'
  };
}

function relatedResources(item) {
  const topics = new Set(item.topics.map((t) => t.toLowerCase()));
  return published
    .filter((other) => other.slug !== item.slug && other.subject === item.subject)
    .map((other) => ({
      other,
      score: other.topics.filter((t) => topics.has(t.toLowerCase())).length * 3
        + (other.level === item.level ? 2 : 0)
        + (other.exam_board && other.exam_board === item.exam_board ? 1 : 0)
    }))
    .filter(({ score }) => score > 0)
    .sort((a, b) => b.score - a.score || b.other.date_published.localeCompare(a.other.date_published))
    .slice(0, 3)
    .map(({ other }) => other);
}

